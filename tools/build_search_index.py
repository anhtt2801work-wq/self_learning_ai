#!/usr/bin/env python3
"""Build assets/js/search-index.js from the headings and text of the site's HTML pages.

Run from the repository root after editing any lesson page:

    python3 tools/build_search_index.py
"""
import json
import re
import sys
import unicodedata
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = [
    ("huong-dan.html", "Cách dùng"),
    ("github.html", "GitHub"),
    ("machine-learning.html", "Machine Learning"),
    ("deep-learning.html", "Deep Learning"),
    ("computer-vision.html", "Computer Vision"),
    ("nlp.html", "NLP"),
    ("llm.html", "LLM"),
    ("agentic-ai.html", "Agentic AI"),
    ("mlops.html", "MLOps"),
    ("ket-hop-cong-cu-ai.html", "Kết hợp AI"),
    ("cyber-security.html", "An ninh mạng"),
    ("quant-trading.html", "Quant Trading"),
]
SKIP = {"script", "style", "pre", "noscript"}
MAX_CHARS = 1400

MATH = re.compile(r"\$\$.*?\$\$|\\\(.*?\\\)|\\\[.*?\\\]", re.S)


class Extractor(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.in_main = False
        self.skip_depth = 0
        self.entries = []      # dicts: id, title, level, parts
        self.cur = None
        self.heading = None    # (level, id, [text parts]) while inside h1/h2/h3

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "main":
            self.in_main = True
        if not self.in_main:
            return
        if tag in SKIP:
            self.skip_depth += 1
        if tag in ("h1", "h2", "h3"):
            self.heading = (int(tag[1]), a.get("id"), [])

    def handle_endtag(self, tag):
        if tag == "main":
            self.in_main = False
        if not self.in_main:
            return
        if tag in SKIP and self.skip_depth:
            self.skip_depth -= 1
        if tag in ("h1", "h2", "h3") and self.heading:
            level, hid, parts = self.heading
            title = " ".join("".join(parts).split())
            self.heading = None
            if level == 1:
                self.cur = {"id": None, "title": title, "parts": []}
                self.entries.append(self.cur)
            elif hid:
                self.cur = {"id": hid, "title": title, "parts": []}
                self.entries.append(self.cur)
            else:
                print(f"warning: heading without id: {title!r}", file=sys.stderr)

    def handle_data(self, data):
        if not self.in_main or self.skip_depth:
            return
        if self.heading:
            self.heading[2].append(data)
        elif self.cur is not None:
            self.cur["parts"].append(data)


def clean(text: str) -> str:
    text = MATH.sub(" … ", text)
    return " ".join(text.split())


def main():
    index = []
    for filename, label in PAGES:
        parser = Extractor()
        parser.feed((ROOT / filename).read_text(encoding="utf-8"))
        for e in parser.entries:
            body = clean(" ".join(e["parts"]))
            url = filename + (f"#{e['id']}" if e["id"] else "")
            title = e["title"]
            if not body and not e["id"]:
                continue
            index.append({"p": label, "t": unicodedata.normalize("NFC", title), "u": url,
                          "x": unicodedata.normalize("NFC", body[:MAX_CHARS])})
    out = ROOT / "assets" / "js" / "search-index.js"
    out.write_text("/* Generated by tools/build_search_index.py. Do not edit by hand. */\n"
                   "window.SEARCH_INDEX = " + json.dumps(index, ensure_ascii=False, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}: {len(index)} entries, {out.stat().st_size // 1024} KiB")


if __name__ == "__main__":
    main()
